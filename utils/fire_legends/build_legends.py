#!/usr/bin/env python3
"""Validate the MapBiomas Fire legend registry and regenerate LEGENDS.md, preview.html and app/palettes.json.

Usage (from this folder):
    python build_legends.py            # validate, then write LEGENDS.md and preview.html
    python build_legends.py --check    # validate only; exit code 1 if anything is wrong

Only the Python standard library is used.
"""
import csv
import html
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REGISTRY = os.path.join(HERE, "registry.csv")
LEGENDS_DIR = os.path.join(HERE, "legends")

REGISTRY_COLUMNS = ["legend_id", "country", "collection", "product", "status", "years",
                    "pixel_meaning", "file", "gee_asset",
                    "app_country", "app_collection", "app_product"]
LEGEND_COLUMNS = ["pixel_value", "name_pt", "name_en", "name_es", "hex"]
STATUSES = {"active", "review", "pending_colors", "deprecated", "not_found"}
HEX_RE = re.compile(r"^#[0-9a-f]{6}$")


def read_csv(path):
    with open(path, encoding="utf-8", newline="") as handle:
        reader = csv.DictReader(handle)
        return reader.fieldnames or [], list(reader)


def load():
    """Return (registry_rows, legends_by_id, errors)."""
    errors = []
    columns, rows = read_csv(REGISTRY)
    if columns != REGISTRY_COLUMNS:
        errors.append(f"registry.csv: columns must be exactly {REGISTRY_COLUMNS}")
        return rows, {}, errors

    seen, legends, used_files = set(), {}, set()
    for number, row in enumerate(rows, start=2):
        where = f"registry.csv line {number} ({row['legend_id'] or '?'})"
        if not row["legend_id"]:
            errors.append(f"{where}: legend_id is empty")
        elif row["legend_id"] in seen:
            errors.append(f"{where}: duplicated legend_id")
        seen.add(row["legend_id"])
        if row["status"] not in STATUSES:
            errors.append(f"{where}: status '{row['status']}' is not one of {sorted(STATUSES)}")
        if row["status"] in ("active", "deprecated") and not row["file"]:
            errors.append(f"{where}: status '{row['status']}' needs a file in legends/")
        if row["file"]:
            if not (row["app_country"] and row["app_collection"] and row["app_product"]):
                errors.append(f"{where}: app_country, app_collection and app_product are required when there is a file")
            used_files.add(row["file"])
            path = os.path.join(LEGENDS_DIR, row["file"])
            if not os.path.isfile(path):
                errors.append(f"{where}: file legends/{row['file']} does not exist")
                continue
            legend_cols, items = read_csv(path)
            if legend_cols != LEGEND_COLUMNS:
                errors.append(f"legends/{row['file']}: columns must be exactly {LEGEND_COLUMNS}")
                continue
            values = set()
            for i, item in enumerate(items, start=2):
                at = f"legends/{row['file']} line {i}"
                if not item["pixel_value"].isdigit():
                    errors.append(f"{at}: pixel_value '{item['pixel_value']}' must be a whole number")
                elif item["pixel_value"] in values:
                    errors.append(f"{at}: duplicated pixel_value {item['pixel_value']}")
                values.add(item["pixel_value"])
                if not HEX_RE.match(item["hex"]):
                    errors.append(f"{at}: hex '{item['hex']}' must look like #a1b2c3 (6 digits, lowercase)")
                if not item["name_pt"].strip() or not item["name_en"].strip():
                    errors.append(f"{at}: name_pt and name_en are required")
            if not items:
                errors.append(f"legends/{row['file']}: no rows")
            legends[row["legend_id"]] = items

    if os.path.isdir(LEGENDS_DIR):
        for name in sorted(os.listdir(LEGENDS_DIR)):
            if name.endswith(".csv") and name not in used_files:
                errors.append(f"legends/{name} is not listed in registry.csv")
    return rows, legends, errors


def markdown(rows, legends):
    out = ["# MapBiomas Fire · Legends", "",
           "_Generated by `build_legends.py` from `registry.csv` and `legends/*.csv`. Do not edit this file by hand._", "",
           "## Registry", "",
           "| Legend | Country | Collection | Product | Status | Years |", "|---|---|---|---|---|---|"]
    for r in rows:
        out.append(f"| `{r['legend_id']}` | {r['country']} | {r['collection']} | {r['product']} | {r['status']} | {r['years']} |")
    for r in rows:
        items = legends.get(r["legend_id"])
        if not items:
            continue
        out += ["", f"## {r['country'].title()} · Collection {r['collection']} · {r['product']}", "",
                f"Pixel value: {r['pixel_meaning']}.", ""]
        out += ["| Pixel | Português | English | Español | HEX |", "|---:|---|---|---|---|"]
        for i in items:
            out.append(f"| {i['pixel_value']} | {i['name_pt']} | {i['name_en']} | {i['name_es']} | `{i['hex']}` |")
    return "\n".join(out) + "\n"


def palettes(rows, legends):
    """palettes.json for the web app: {country__collection__product: palette}."""
    out = {}
    for r in rows:
        items = legends.get(r["legend_id"])
        if not items:
            continue
        classes = []
        for i in items:
            c = {"v": int(i["pixel_value"]), "hex": i["hex"], "src": "oficial"}
            c.update({"pt": i["name_pt"], "en": i["name_en"], "es": i["name_es"]})
            classes.append(c)
        key = f"{r['app_country']}__{r['app_collection']}__{r['app_product']}"
        out[key] = {"country": r["app_country"], "collection": r["app_collection"], "subproduct": r["app_product"],
                    "classes": classes, "expected": len(classes),
                    "status": "validada" if r["status"] == "active" else "revisao",
                    "updatedAt": "from-repository"}
    return json.dumps(out, ensure_ascii=False, indent=1, sort_keys=True) + "\n"


def preview(rows, legends):
    esc = html.escape
    parts = ["<!doctype html><html lang='en'><meta charset='utf-8'><title>MapBiomas Fire · Legends</title>",
             "<style>body{font:14px system-ui,sans-serif;margin:24px;max-width:900px}table{border-collapse:collapse;margin:8px 0 24px}"
             "td,th{border:1px solid #ddd;padding:4px 10px;text-align:left}th{background:#f3f3f3}"
             ".sw{width:64px}code{font-size:12px}.note{color:#555}</style>",
             "<h1>MapBiomas Fire · Legends</h1><p class='note'>Generated by build_legends.py.</p>"]
    for r in rows:
        items = legends.get(r["legend_id"])
        if not items:
            continue
        parts.append(f"<h2>{esc(r['country'].title())} · Collection {esc(r['collection'])} · {esc(r['product'])}</h2>")
        parts.append(f"<p class='note'>Pixel value: {esc(r['pixel_meaning'])}.</p>")
        parts.append("<table><tr><th>Pixel</th><th>PT</th><th>EN</th><th>ES</th><th>HEX</th><th>Color</th></tr>")
        for i in items:
            parts.append(f"<tr><td>{esc(i['pixel_value'])}</td><td>{esc(i['name_pt'])}</td><td>{esc(i['name_en'])}</td>"
                         f"<td>{esc(i['name_es'])}</td><td><code>{esc(i['hex'])}</code></td>"
                         f"<td class='sw' style='background:{esc(i['hex'])}'></td></tr>")
        parts.append("</table>")
    return "\n".join(parts) + "\n"


def main(argv):
    rows, legends, errors = load()
    if errors:
        print(f"{len(errors)} problem(s) found:")
        for e in errors:
            print(" -", e)
        return 1
    n_colors = sum(len(v) for v in legends.values())
    print(f"OK: {len(rows)} legends in the registry, {len(legends)} with colors ({n_colors} classes).")
    if "--check" in argv:
        return 0
    for name, text in (("LEGENDS.md", markdown(rows, legends)), ("preview.html", preview(rows, legends)),
                       (os.path.join("app", "palettes.json"), palettes(rows, legends))):
        with open(os.path.join(HERE, name), "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        print("wrote", name)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
